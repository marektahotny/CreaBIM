/// The rolled sections offered, in SI units.
pub fn rolled() -> Vec<SectionData> {
    STAD.iter()
        .chain(FERONA.iter())
        .map(
            |&(name, shape, g, [h, b, tw, tf, r], a, [iy, wy], wply, [iz, wz], wplz)| SectionData {
                name: name.into(),
                shape,
                h: h / 1000.0,
                b: b / 1000.0,
                tw: tw / 1000.0,
                tf: tf / 1000.0,
                r: r / 1000.0,
                area: a * 1e-4,
                iy: iy * 1e-8,
                iz: iz * 1e-8,
                wy: wy * 1e-6,
                wz: wz * 1e-6,
                wply: wply.map(|v| v * 1e-6),
                wplz: wplz.map(|v| v * 1e-6),
                mass: Some(g),
                source: if FERONA.iter().any(|r| r.0 == name) {
                    "Ferona"
                } else {
                    "STAD"
                },
            },
        )
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn hea_160_is_as_stad_prints_it() {
        let s = rolled().into_iter().find(|s| s.name == "HEA 160").unwrap();
        assert_eq!(s.mass, Some(30.4));
        assert!((s.h - 0.152).abs() < 1e-12 && (s.b - 0.16).abs() < 1e-12);
        assert!((s.iy - 1673e-8).abs() < 1e-14);
        assert_eq!(rolled().len(), 45 + 22);
        // the carport's report: K80/50/3, Ferona 5,495 kg/m
        let r = rolled()
            .into_iter()
            .find(|s| s.name == "RHS 80×50×3")
            .unwrap();
        assert_eq!((r.mass, r.source), (Some(5.495), "Ferona"));
    }
}
