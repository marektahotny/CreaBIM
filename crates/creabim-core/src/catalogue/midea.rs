/// The maximum heating output, kW, at outside temperature `db` (a row
/// of the table) and leaving water `lwt`, between the table's columns
/// in a line; none outside the unit's range.
pub fn max_at(size: u32, row: usize, lwt: f64) -> Option<f64> {
    let t = &MAX.iter().find(|x| x.0 == arctic(size).size)?.1[row];
    let lwt = lwt.clamp(LWT[0], LWT[LWT.len() - 1]);
    let j = LWT.iter().rposition(|c| *c <= lwt + 1e-9)?;
    let a = t[j].0;
    if j + 1 >= LWT.len() || (lwt - LWT[j]).abs() < 1e-9 {
        return (a >= 0.0).then_some(a);
    }
    let b = t[j + 1].0;
    if a < 0.0 || b < 0.0 {
        return None;
    }
    Some(a + (b - a) * (lwt - LWT[j]) / (LWT[j + 1] - LWT[j]))
}

/// The output curve at flow temperature `t_flow`: (outside °C, kW) for
/// every row of the table the unit runs at.
pub fn curve(size: u32, t_flow: f64) -> Vec<(f64, f64)> {
    (0..DB.len())
        .filter_map(|r| max_at(size, r, t_flow).map(|q| (DB[r], q)))
        .collect()
}

